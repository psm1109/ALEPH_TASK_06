create or replace function public.record_task_completion_once()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.is_completed = true and old.is_completed = false then
    insert into public.task_completion_events (workspace_id, task_id, completed_at)
    values (new.workspace_id, new.id, coalesce(new.completed_at, now()))
    on conflict (workspace_id, task_id) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists tasks_record_completion_once on public.tasks;
create trigger tasks_record_completion_once
after update of is_completed on public.tasks
for each row execute function public.record_task_completion_once();

insert into public.task_completion_events (workspace_id, task_id, completed_at)
select workspace_id, id, coalesce(completed_at, updated_at, now())
from public.tasks
where is_completed = true
on conflict (workspace_id, task_id) do nothing;

